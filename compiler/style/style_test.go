func loadStyleFixture(
	t *testing.T,
	files map[string]string,
) (*load.Program, resolve.Result, provider.Catalog) {
	t.Helper()
	root := t.TempDir()
	core := testsupport.CoreDirectory(t)
	allFiles := map[string]string{
		"go.mod": "module example.com/style\n\ngo 1.26.0\n\n" +
			"require github.com/spice-framework/spice v0.0.0\n\n" +
			"replace github.com/spice-framework/spice => " +
			filepath.ToSlash(core) + "\n",
	}
	maps.Copy(allFiles, files)
	paths := make([]string, 0, len(allFiles))
	for name := range allFiles {
		paths = append(paths, name)
	}
	sort.Strings(paths)
	for _, name := range paths {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(allFiles[name]), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	program, err := load.Load(
		context.Background(),
		load.Options{Dir: root},
		"./app",
	)
	if err != nil {
		t.Fatalf("load.Load() error = %v", err)
	}
	resolution := resolve.Annotations(program)
	if len(resolution.Diagnostics) != 0 {
		t.Fatalf("resolve.Annotations() diagnostics = %v", resolution.Diagnostics)
	}
	resolution, err = testannotation.AttachOfficial(resolution)
	if err != nil {
		t.Fatalf("AttachOfficial() error = %v", err)
	}
	providers := provider.Build(program, resolution)
	if diagnostics := providers.Diagnostics(); len(diagnostics) != 0 {
		t.Fatalf("provider.Build() diagnostics = %v", diagnostics)
	}
	return program, resolution, providers
}

func containsKind(diagnostics []Diagnostic, wanted string) bool {
	for _, diagnostic := range diagnostics {
		if diagnostic.Kind == wanted {
			return true
		}
	}
	return false
}

func diagnosticStrings(diagnostics []Diagnostic) []string {
	result := make([]string, len(diagnostics))
	for index, diagnostic := range diagnostics {
		result[index] = diagnostic.Error()
	}
	return result
}
