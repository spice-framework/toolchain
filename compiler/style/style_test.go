func TestBuildAcceptsJavaStructuredSource(t *testing.T) {
	program, resolution, providers := loadStyleFixture(t, map[string]string{
		"app/doc.go": `// Package app owns workers.
package app
`,
		"app/runner.go": `package app

type Runner interface {
	Run()
}
`,
		"app/worker.go": `package app

// @Component
// @Implements(Runner)
type Worker struct{}

func NewWorker() *Worker { return &Worker{} }

func (*Worker) Run() {}
`,
		"app/status.go": `package app

// @Enum
type Status string

const StatusReady Status = "ready"

func ParseStatus(value string) (Status, bool) {
	status := Status(value)
	return status, status.Valid()
}

func (status Status) Valid() bool { return status == StatusReady }
`,
		"app/external.go": `package app

type External struct{}
`,
		"app/external_bean.go": `package app

// @Bean
func NewExternalBean() *External { return &External{} }
`,
		"app/event.go": `package app

type Event struct{}
`,
		"app/event_topic.go": `package app

import "github.com/spice-framework/spice/event"

// @event.Topic
func EventTopic() event.Publisher[Event] { panic("metadata only") }
`,
		"app/generated.go": `// Code generated by a test. DO NOT EDIT.
package app

type GeneratedOne struct{}
type GeneratedTwo struct{}
func helper() {}
`,
		"app/worker_test.go": `package app

type TestOnlyOne struct{}
type TestOnlyTwo struct{}
func testHelper() {}
`,
	})
	diagnostics := Build(
		program,
		resolution,
		providers,
		ProfileJavaStructured,
	).Diagnostics()
	if len(diagnostics) != 0 {
		t.Fatalf("Build() diagnostics = %v", diagnosticStrings(diagnostics))
	}
}

func TestBuildRejectsJavaStructuredViolations(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		want  string
	}{
		{
			name: "one type per file",
			files: map[string]string{
				"app/types.go": "package app\n\ntype First struct{}\ntype Second struct{}\n",
			},
			want: "file.one-primary-type",
		},
		{
			name: "receiver colocation",
			files: map[string]string{
				"app/worker.go":        "package app\n\ntype Worker struct{}\n",
				"app/worker_method.go": "package app\n\nfunc (*Worker) Run() {}\n",
			},
			want: "file.method-owner",
		},
		{
			name: "free function",
			files: map[string]string{
				"app/worker.go": "package app\n\ntype Worker struct{}\n\nfunc normalize() {}\n",
			},
			want: "function.package-level",
		},
		{
			name: "package bean",
			files: map[string]string{
				"app/dependency.go": "package app\n\ntype Dependency struct{}\n\n// @Bean\nfunc NewDependency() *Dependency { return &Dependency{} }\n",
			},
			want: "function.package-level",
		},
		{
			name: "function topic",
			files: map[string]string{
				"app/event.go": `package app

import "github.com/spice-framework/spice/event"

type Event struct{}

// @event.Topic
func EventTopic() event.Publisher[Event] { panic("metadata only") }
`,
			},
			want: "function.package-level",
		},
		{
			name: "generic constructor",
			files: map[string]string{
				"app/worker.go": "package app\n\n// @Service\ntype Worker struct{}\n\nfunc New() *Worker { return &Worker{} }\n",
			},
			want: "constructor.name",
		},
		{
			name: "missing explicit constructor",
			files: map[string]string{
				"app/worker.go": "package app\n\n// @Service\ntype Worker struct{}\n",
			},
			want: "constructor.explicit",
		},
		{
			name: "constructor file",
			files: map[string]string{
				"app/worker.go":             "package app\n\n// @Service\ntype Worker struct{}\n",
				"app/worker_constructor.go": "package app\n\nfunc NewWorker() *Worker { return &Worker{} }\n",
			},
			want: "constructor.location",
		},
		{
			name: "package file declaration",
			files: map[string]string{
				"app/doc.go": "package app\n\nconst Name = \"app\"\n",
			},
			want: "file.unrelated-declaration",
		},
		{
			name: "mutable global",
			files: map[string]string{
				"app/value.go": "package app\n\nvar value int\n",
			},
			want: "package.mutable-global",
		},
		{
			name: "init",
			files: map[string]string{
				"app/value.go": "package app\n\nfunc init() {}\n",
			},
			want: "function.init",
		},
		{
			name: "implicit managed interface",
			files: map[string]string{
				"app/runner.go": "package app\n\ntype Runner interface { Run() }\n",
				"app/worker.go": "package app\n\n// @Component\ntype Worker struct{}\n\nfunc (*Worker) Run() {}\n",
			},
			want: "bean.interface-binding",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			program, resolution, providers := loadStyleFixture(t, test.files)
			diagnostics := Build(
				program,
				resolution,
				providers,
				ProfileJavaStructured,
			).Diagnostics()
			if !containsKind(diagnostics, test.want) {
				t.Fatalf(
					"Build() diagnostics = %v, want kind %q",
					diagnosticStrings(diagnostics),
					test.want,
				)
			}
		})
	}
}

