func buildApplication(
	t *testing.T,
	root string,
	patterns ...string,
) (*load.Program, application.Model, application.Target) {
	t.Helper()
	program, err := load.Load(context.Background(), load.Options{Dir: root}, patterns...)
	if err != nil {
		t.Fatalf("load.Load() error = %v", err)
	}
	resolution := resolve.Annotations(program)
	if len(resolution.Diagnostics) != 0 {
		t.Fatalf("resolve.Annotations() diagnostics = %v", resolution.Diagnostics)
	}
	model := application.Build(program, resolution)
	if diagnostics := model.Diagnostics(); len(diagnostics) != 0 {
		t.Fatalf("application.Build() diagnostics = %v", applicationDiagnosticStrings(diagnostics))
	}
	targets := model.Targets()
	if len(targets) != 1 {
		t.Fatalf("Targets() = %#v, want one", targets)
	}
	return program, model, targets[0]
}

func writeModule(t *testing.T, modulePath string, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	repository := repositoryRoot(t)
	goMod := "module " + modulePath + "\n\ngo 1.26.0\n\n" +
		"require github.com/StevenBuglione/spice v0.0.0\n\n" +
		"replace github.com/StevenBuglione/spice => " + filepath.ToSlash(repository) + "\n"
	writeTestFile(t, root, "go.mod", goMod)
	paths := make([]string, 0, len(files))
	for file := range files {
		paths = append(paths, file)
	}
	sort.Strings(paths)
	for _, file := range paths {
		writeTestFile(t, root, file, files[file])
	}
	return root
}

func writePlan(t *testing.T, root string, plan Plan) {
	t.Helper()
	for _, file := range plan.Files() {
		writeTestFile(t, root, file.Path, string(file.Content()))
	}
	writeTestFile(t, root, plan.Target().ManifestPath, string(plan.ManifestContent()))
}

func writeTestFile(t *testing.T, root, relativePath, content string) {
	t.Helper()
	fullPath := filepath.Join(root, filepath.FromSlash(relativePath))
	if err := os.MkdirAll(filepath.Dir(fullPath), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(fullPath, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func repositoryRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatalf("filepath.Abs() error = %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "go.mod")); err != nil {
		t.Fatalf("repository root %q: %v", root, err)
	}
	return root
}

func runGoTest(t *testing.T, root string, patterns ...string) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	arguments := append([]string{"test", "-mod=mod", "-count=1"}, patterns...)
	command := exec.CommandContext(ctx, "go", arguments...)
	command.Dir = root
	command.Env = append(os.Environ(), "GOWORK=off", "GOPROXY=off")
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("go %s: %v\n%s", strings.Join(arguments, " "), err, output)
	}
}

func assertOrdered(t *testing.T, content string, values ...string) {
	t.Helper()
	previous := -1
	for _, value := range values {
		index := strings.Index(content, value)
		if index <= previous {
			t.Fatalf("%q is not ordered after prior values in:\n%s", value, content)
		}
		previous = index
	}
}

func containsGenerationDiagnostic(diagnostics []Diagnostic, text string) bool {
	for _, diagnostic := range diagnostics {
		if strings.Contains(diagnostic.Message, text) {
			return true
		}
	}
	return false
}

func generationDiagnosticStrings(diagnostics []Diagnostic) []string {
	result := make([]string, len(diagnostics))
	for index, diagnostic := range diagnostics {
		result[index] = diagnostic.Error()
	}
	return result
}

func applicationDiagnosticStrings(diagnostics []application.Diagnostic) []string {
	result := make([]string, len(diagnostics))
	for index, diagnostic := range diagnostics {
		result[index] = diagnostic.Error()
	}
	return result
}
