func TestRenderRejectsInvalidInputs(t *testing.T) {
	root := writeModule(t, "example.com/inputs", map[string]string{
		"app/application.go": `package app

// @Application
func Application() {}
`,
	})
	program, model, applicationTarget := buildApplication(t, root, "./...")
	valid, diagnostics := DefaultTarget(program, applicationTarget)
	if len(diagnostics) != 0 {
		t.Fatalf("DefaultTarget() diagnostics = %v", generationDiagnosticStrings(diagnostics))
	}

	if _, nilDiagnostics := Render(nil, model, applicationTarget, valid); len(nilDiagnostics) != 1 {
		t.Fatalf("Render(nil) diagnostics = %#v", nilDiagnostics)
	}
	invalidModel := application.Build(nil, resolve.Result{})
	if _, modelDiagnostics := Render(program, invalidModel, applicationTarget, valid); len(modelDiagnostics) != 1 ||
		!containsGenerationDiagnostic(modelDiagnostics, "model has 1 diagnostic") {
		t.Fatalf("Render(invalid model) diagnostics = %#v", modelDiagnostics)
	}
	if _, unknownDiagnostics := Render(program, model, application.Target{}, valid); len(unknownDiagnostics) != 1 ||
		unknownDiagnostics[0].Kind != "unknown-target" {
		t.Fatalf("Render(unknown target) diagnostics = %#v", unknownDiagnostics)
	}

	invalid := Target{ID: "Not-Portable"}
	if _, targetDiagnostics := Render(program, model, applicationTarget, invalid); len(targetDiagnostics) != 6 {
		t.Fatalf("Render(invalid target) diagnostics = %v, want 6", generationDiagnosticStrings(targetDiagnostics))
	}
	if _, defaultDiagnostics := DefaultTarget(nil, applicationTarget); len(defaultDiagnostics) != 1 {
		t.Fatalf("DefaultTarget(nil) diagnostics = %#v", defaultDiagnostics)
	}
	if _, moduleDiagnostics := DefaultTarget(&load.Program{}, applicationTarget); len(moduleDiagnostics) != 1 ||
		moduleDiagnostics[0].Kind != "module" {
		t.Fatalf("DefaultTarget(no module) diagnostics = %#v", moduleDiagnostics)
	}
}

func TestPlanAccessorsReturnDefensiveCopies(t *testing.T) {
	root := writeModule(t, "example.com/copies", map[string]string{
		"app/application.go": `package app

// @Application
func Application() {}
`,
	})
	program, model, applicationTarget := buildApplication(t, root, "./...")
	target, diagnostics := DefaultTarget(program, applicationTarget)
	if len(diagnostics) != 0 {
		t.Fatalf("DefaultTarget() diagnostics = %v", generationDiagnosticStrings(diagnostics))
	}
	plan, diagnostics := Render(program, model, applicationTarget, target)
	if len(diagnostics) != 0 {
		t.Fatalf("Render() diagnostics = %v", generationDiagnosticStrings(diagnostics))
	}

	files := plan.Files()
	files[0].content[0] = 'X'
	content := files[0].Content()
	content[0] = 'Y'
	if plan.Files()[0].Content()[0] != '/' {
		t.Fatal("Files or File.Content returned mutable storage")
	}
	manifest := plan.Manifest()
	manifest.Files[0].Path = "changed"
	if plan.Manifest().Files[0].Path == "changed" {
		t.Fatal("Manifest returned mutable file storage")
	}
	manifestContent := plan.ManifestContent()
	manifestContent[0] = 'X'
	if plan.ManifestContent()[0] != '{' {
		t.Fatal("ManifestContent returned mutable storage")
	}
	if plan.Target() != target {
		t.Fatalf("Target() = %#v, want %#v", plan.Target(), target)
	}
}

