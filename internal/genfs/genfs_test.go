func addManifestFile(t *testing.T, root string, plan generate.Plan, file generate.ManifestFile) {
	t.Helper()
	manifestPath := filepath.Join(root, filepath.FromSlash(plan.Target().ManifestPath))
	content := mustRead(t, manifestPath)
	var manifest generate.Manifest
	if err := json.Unmarshal(content, &manifest); err != nil {
		t.Fatal(err)
	}
	manifest.Files = append(manifest.Files, file)
	writeManifest(t, manifestPath, manifest)
}

func writeManifest(t *testing.T, filePath string, manifest generate.Manifest) {
	t.Helper()
	content, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, filePath, append(content, '\n'))
}

func hasDifference(status Status, kind DifferenceKind) bool {
	for _, difference := range status.Differences {
		if difference.Kind == kind {
			return true
		}
	}
	return false
}

func mustStat(t *testing.T, filePath string) fs.FileInfo {
	t.Helper()
	info, err := os.Stat(filePath)
	if err != nil {
		t.Fatal(err)
	}
	return info
}

func mustRead(t *testing.T, filePath string) []byte {
	t.Helper()
	content, err := os.ReadFile(filePath)
	if err != nil {
		t.Fatal(err)
	}
	return content
}

func writeFile(t *testing.T, filePath string, content []byte) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(filePath), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filePath, content, 0o600); err != nil {
		t.Fatal(err)
	}
}

func bytesEqual(left, right []byte) bool {
	return slices.Equal(left, right)
}
