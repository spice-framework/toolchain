func TestApplyCreatesChecksAndPreservesUnchangedFiles(t *testing.T) {
	root := generationModule(t)
	plan := renderPlan(t, root, applicationSource)

	status, err := Check(plan)
	if err != nil {
		t.Fatalf("Check() error = %v", err)
	}
	if status.Current ||
		!hasDifference(status, DifferenceMissingManifest) ||
		!hasDifference(status, DifferenceMissingFile) {
		t.Fatalf("initial Check() = %#v", status)
	}
	diff, err := Diff(plan)
	if err != nil {
		t.Fatalf("Diff() error = %v", err)
	}
	for _, expected := range []string{
		"--- a/internal/spicegen/application/spice_assembly_gen.go",
		"+++ b/internal/spicegen/application/spice_assembly_gen.go",
		"+// Code generated by Spice. DO NOT EDIT.",
	} {
		if !strings.Contains(diff, expected) {
			t.Fatalf("Diff() missing %q:\n%s", expected, diff)
		}
	}

	result, err := Apply(plan)
	if err != nil {
		t.Fatalf("Apply() error = %v", err)
	}
	if !result.Changed() ||
		!result.ManifestUpdated ||
		!slices.Equal(result.Written, generatedPaths(plan)) ||
		len(result.Removed) != 0 {
		t.Fatalf("Apply() = %#v", result)
	}
	generatedPath := filepath.Join(
		root,
		"internal",
		"spicegen",
		"application",
		"spice_assembly_gen.go",
	)
	manifestPath := filepath.Join(root, ".spice", "application.manifest.json")
	generatedInfo := mustStat(t, generatedPath)
	manifestInfo := mustStat(t, manifestPath)

	status, err = Check(plan)
	if err != nil || !status.Current || len(status.Differences) != 0 {
		t.Fatalf("current Check() = %#v, %v", status, err)
	}
	if diff, err = Diff(plan); err != nil || diff != "" {
		t.Fatalf("current Diff() = %q, %v", diff, err)
	}
	result, err = Apply(plan)
	if err != nil {
		t.Fatalf("second Apply() error = %v", err)
	}
	if result.Changed() {
		t.Fatalf("second Apply() = %#v, want no changes", result)
	}
	if got := mustStat(t, generatedPath).ModTime(); !got.Equal(generatedInfo.ModTime()) {
		t.Fatalf("unchanged generated mtime = %v, want %v", got, generatedInfo.ModTime())
	}
	if got := mustStat(t, manifestPath).ModTime(); !got.Equal(manifestInfo.ModTime()) {
		t.Fatalf("unchanged manifest mtime = %v, want %v", got, manifestInfo.ModTime())
	}
	if _, err := os.Stat(filepath.Join(root, ".spice", "application.lock")); !errors.Is(err, fs.ErrNotExist) {
		t.Fatalf("generation lock remains after Apply: %v", err)
	}
}

func TestApplyApplicationPackagePreservesHandwrittenSource(t *testing.T) {
	tests := []struct {
		name       string
		sourcePath string
		pattern    string
		outputDir  string
	}{
		{
			name:       "nested command",
			sourcePath: "cmd/shop/main.go",
			pattern:    "./...",
			outputDir:  "internal/spicegen/shop",
		},
		{
			name:       "module root command",
			sourcePath: "main.go",
			pattern:    ".",
			outputDir:  "internal/spicegen/genfs",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := generationModule(t)
			targetID := path.Base(path.Dir(test.sourcePath))
			if path.Dir(test.sourcePath) == "." {
				targetID = "genfs"
			}
			source := mainApplicationSource(targetID)
			plan := renderMainPlan(
				t,
				root,
				test.sourcePath,
				test.pattern,
				source,
			)
			if plan.Target().Layout != generate.LayoutApplicationPackage ||
				plan.Target().OutputDir != test.outputDir ||
				plan.Target().BridgeDir !=
					path.Dir(filepath.ToSlash(test.sourcePath)) {
				t.Fatalf("Target() = %#v", plan.Target())
			}
			result, err := Apply(plan)
			if err != nil {
				t.Fatalf("Apply() error = %v", err)
			}
			if !result.Changed() {
				t.Fatalf("Apply() = %#v", result)
			}
			sourcePath := filepath.Join(
				root,
				filepath.FromSlash(test.sourcePath),
			)
			if content := mustRead(t, sourcePath); !slices.Equal(content, source) {
				t.Fatalf("handwritten source changed:\n%s", content)
			}
			status, err := Check(plan)
			if err != nil || !status.Current {
				t.Fatalf("Check() = %#v, %v", status, err)
			}
		})
	}
}

