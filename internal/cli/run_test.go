func runModule(root string, arguments ...string) (int, string, string) {
	var stdout, stderr bytes.Buffer
	code := run(arguments, &stdout, &stderr, load.Options{Dir: root}, load.Load)
	return code, stdout.String(), stderr.String()
}

func writeGoSource(t *testing.T, source string) string {
	t.Helper()
	return writeModule(t, map[string]string{"sample.go": source})
}

func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	normalized := make(map[string]string, len(files))
	usesAnnotations := false
	for path, source := range files {
		if filepath.Ext(path) == ".go" {
			source, usesAnnotations = withTestAnnotationImports(
				source,
				usesAnnotations,
			)
		}
		normalized[path] = source
	}
	goMod := normalized["go.mod"]
	if goMod == "" {
		goMod = "module example.com/fixture\n\ngo 1.26.0\n"
	}
	if usesAnnotations {
		goMod = withTestAnnotationTool(t, goMod)
	}
	if err := os.WriteFile(
		filepath.Join(root, "go.mod"),
		[]byte(goMod),
		0o600,
	); err != nil {
		t.Fatal(err)
	}
	for path, source := range normalized {
		if path == "go.mod" {
			continue
		}
		full := filepath.Join(root, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func withTestAnnotationImports(
	source string,
	alreadyFound bool,
) (string, bool) {
	if strings.Contains(source, "// @import") {
		return source, true
	}
	type descriptorImport struct {
		symbols   []string
		namespace string
		path      string
	}
	imports := []descriptorImport{
		{
			symbols: []string{
				"Application",
				"Bean",
				"Configuration",
				"Fallback",
				"Implements",
				"Order",
				"Primary",
				"Prototype",
				"Qualifier",
				"Repository",
				"RequestScope",
				"Service",
				"SessionScope",
				"Singleton",
			},
			path: "github.com/spice-framework/spice/annotation/core",
		},
		{
			symbols: []string{"OnStart", "OnStop"},
			path:    "github.com/spice-framework/spice/annotation/lifecycle",
		},
		{
			symbols: []string{"Module", "NamedInterface"},
			path:    "github.com/spice-framework/spice/annotation/modulith",
		},
		{
			symbols: []string{"Controller", "Get", "Post"},
			path:    "github.com/spice-framework/spice/annotation/web",
		},
		{
			namespace: "async",
			path:      "github.com/spice-framework/spice/annotation/async",
		},
		{
			namespace: "cache",
			path:      "github.com/spice-framework/spice/annotation/cache",
		},
		{
			namespace: "data",
			path:      "github.com/spice-framework/spice/annotation/data",
		},
		{
			namespace: "event",
			path:      "github.com/spice-framework/spice/annotation/event",
		},
		{
			namespace: "management",
			path:      "github.com/spice-framework/spice/annotation/management",
		},
		{
			namespace: "observability",
			path:      "github.com/spice-framework/spice/annotation/observability",
		},
		{
			namespace: "schedule",
			path:      "github.com/spice-framework/spice/annotation/schedule",
		},
		{
			namespace: "security",
			path:      "github.com/spice-framework/spice/annotation/security",
		},
	}
	var directives []string
	for _, item := range imports {
		if item.namespace != "" {
			if strings.Contains(
				source,
				"// @"+item.namespace+".",
			) {
				directives = append(
					directives,
					"// @import * as "+item.namespace+
						` from "`+item.path+`"`,
				)
			}
			continue
		}
		var selected []string
		for _, symbol := range item.symbols {
			if strings.Contains(source, "// @"+symbol) {
				selected = append(selected, symbol)
			}
		}
		if len(selected) != 0 {
			directives = append(
				directives,
				"// @import { "+strings.Join(selected, ", ")+
					` } from "`+item.path+`"`,
			)
		}
	}
	if len(directives) == 0 {
		return source, alreadyFound
	}
	return strings.TrimRight(source, "\r\n") + "\n\n" +
		strings.Join(directives, "\n") + "\n", true
}

func withTestAnnotationTool(t *testing.T, content string) string {
	t.Helper()
	file, parseErr := modfile.Parse("go.mod", []byte(content), nil)
	if parseErr != nil {
		t.Fatalf("parse fixture go.mod: %v", parseErr)
	}
	if err := file.AddGoStmt("1.26.0"); err != nil {
		t.Fatalf("set fixture Go version: %v", err)
	}
	if err := file.AddTool(identity.AnnotationTool); err != nil {
		t.Fatalf("authorize fixture annotation tool: %v", err)
	}
	if file.Module == nil || file.Module.Mod.Path != identity.ToolchainModule {
		if err := file.AddRequire(identity.CoreModule, identity.CoreVersion); err != nil {
			t.Fatalf("require fixture Spice core: %v", err)
		}
		if err := file.AddRequire(identity.ToolchainModule, "v0.0.0"); err != nil {
			t.Fatalf("require fixture toolchain: %v", err)
		}
		if err := file.DropReplace(identity.CoreModule, ""); err != nil {
			t.Fatalf("drop fixture core replacement: %v", err)
		}
		if err := file.AddReplace(
			identity.CoreModule,
			"",
			filepath.ToSlash(testsupport.CoreDirectory(t)),
			"",
		); err != nil {
			t.Fatalf("replace fixture Spice core: %v", err)
		}
		repository, resolveErr := filepath.Abs(filepath.Join("..", ".."))
		if resolveErr != nil {
			t.Fatal(resolveErr)
		}
		if err := file.DropReplace(identity.ToolchainModule, ""); err != nil {
			t.Fatalf("drop fixture toolchain replacement: %v", err)
		}
		if err := file.AddReplace(
			identity.ToolchainModule,
			"",
			filepath.ToSlash(repository),
			"",
		); err != nil {
			t.Fatalf("replace fixture toolchain: %v", err)
		}
	}
	formatted, formatErr := file.Format()
	if formatErr != nil {
		t.Fatalf("format fixture go.mod: %v", formatErr)
	}
	return string(formatted)
}

type errorWriter struct{}

func (errorWriter) Write([]byte) (int, error) {
	return 0, errors.New("write failed")
}

type failAfterWriter struct {
	writesRemaining int
}

func (writer *failAfterWriter) Write(data []byte) (int, error) {
	if writer.writesRemaining == 0 {
		return 0, errors.New("write failed")
	}
	writer.writesRemaining--
	return len(data), nil
}

type diagnosticStub struct {
	message string
}

func (diagnostic diagnosticStub) Error() string {
	return diagnostic.message
}
