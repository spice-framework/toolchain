func TestPetclinicDevelopmentWorkflowKeepsLastKnownGoodAndRestarts(
	t *testing.T,
) {
	root := copyPetclinicDevelopmentModule(t)
	t.Setenv("GOWORK", "off")
	t.Setenv("SPICE_PETCLINIC_ADDRESS", "127.0.0.1:0")

	mainPath := filepath.Join(root, "main.go")
	original, err := os.ReadFile(mainPath) // #nosec G304 -- test-owned root.
	if err != nil {
		t.Fatalf("ReadFile(main.go) error = %v", err)
	}
	output := newNotifyingBuffer()
	ctx, cancel := context.WithCancel(context.Background())
	done := make(chan int, 1)
	finished := false
	t.Cleanup(func() {
		if finished {
			return
		}
		cancel()
		select {
		case <-done:
		case <-time.After(30 * time.Second):
			t.Error("timed out cleaning up Petclinic dev process")
		}
	})
	go func() {
		done <- devCommandContext(
			ctx,
			[]string{
				"--target=Petclinic",
				"--poll=20ms",
				"--quiet=20ms",
				"--max-delay=100ms",
				"--stop-timeout=10s",
				".",
				"./memory",
				"./model",
				"./owner",
				"./presentation",
				"./system",
				"./vet",
			},
			strings.NewReader(""),
			output,
			output,
			load.Options{Dir: root, Env: os.Environ()},
			load.Load,
			executeApplicationBuild,
		)
	}()
	waitForBufferText(t, output, "application started (revision 1)")
	waitForBufferText(t, output, `"msg":"Spice application starting"`)

	broken := strings.Replace(
		string(original),
		"// @Application",
		"// @Application\n// @Unknown",
		1,
	)
	if writeErr := os.WriteFile(mainPath, []byte(broken), 0o600); writeErr != nil {
		t.Fatalf("WriteFile(broken main.go) error = %v", writeErr)
	}
	waitForBufferText(t, output, "revision 2 failed")
	waitForBufferText(t, output, "last-known-good revision 1")

	if writeErr := os.WriteFile(mainPath, original, 0o600); writeErr != nil {
		t.Fatalf("WriteFile(fixed main.go) error = %v", writeErr)
	}
	waitForBufferText(t, output, "graceful restart requested for revision 3")
	waitForBufferText(t, output, "application started (revision 3)")

	cancel()
	select {
	case code := <-done:
		finished = true
		if code != 0 {
			t.Fatalf("devCommandContext() code = %d\n%s", code, output.String())
		}
	case <-time.After(30 * time.Second):
		t.Fatalf("timed out waiting for Petclinic dev shutdown\n%s", output.String())
	}

	actual, err := os.ReadFile(mainPath) // #nosec G304 -- test-owned root.
	if err != nil {
		t.Fatalf("ReadFile(restored main.go) error = %v", err)
	}
	if string(actual) != string(original) ||
		!strings.Contains(string(actual), "// @Application") {
		t.Fatal("Petclinic dev changed the handwritten application source")
	}
	bridge, err := os.ReadFile( // #nosec G304 -- test-owned root.
		filepath.Join(root, "zz_spice_bridge_gen.go"),
	)
	if err != nil {
		t.Fatalf("ReadFile(generated bridge) error = %v", err)
	}
	if !strings.HasPrefix(
		string(bridge),
		"//go:build !spice_generate\n\n"+
			"// Code generated by Spice. DO NOT EDIT.\n",
	) || !strings.Contains(string(bridge), "func spiceMain(") {
		t.Fatalf("generated bridge is not canonical:\n%s", bridge)
	}
	for _, formerFailure := range []string{
		"invalid character U+0040 '@'",
		"expected declaration, found 'ILLEGAL'",
		"undefined: spiceMain",
		"gocommand-",
	} {
		if strings.Contains(output.String(), formerFailure) {
			t.Fatalf("Petclinic dev repeated %q:\n%s", formerFailure, output.String())
		}
	}
}

func copyPetclinicDevelopmentModule(t *testing.T) string {
	t.Helper()
	repository, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatalf("resolve repository root: %v", err)
	}
	source := filepath.Join(repository, "examples", "petclinic")
	destination := t.TempDir()
	for _, directory := range []string{
		"memory",
		"model",
		"owner",
		"presentation",
		"system",
		"vet",
	} {
		if err := os.CopyFS(
			filepath.Join(destination, directory),
			os.DirFS(filepath.Join(source, directory)),
		); err != nil {
			t.Fatalf("copy Petclinic %s: %v", directory, err)
		}
	}
	for _, name := range []string{"go.mod", "go.sum", "main.go"} {
		content, readErr := os.ReadFile( // #nosec G304 -- repository fixture.
			filepath.Join(source, name),
		)
		if readErr != nil {
			t.Fatalf("read Petclinic %s: %v", name, readErr)
		}
		if name == "go.mod" {
			content = []byte(strings.Replace(
				string(content),
				"replace github.com/StevenBuglione/spice => ../..",
				"replace github.com/StevenBuglione/spice => "+
					filepath.ToSlash(repository),
				1,
			))
		}
		if writeErr := os.WriteFile(
			filepath.Join(destination, name),
			content,
			0o600,
		); writeErr != nil {
			t.Fatalf("write Petclinic %s: %v", name, writeErr)
		}
	}
	if err := filepath.WalkDir(
		destination,
		func(path string, entry fs.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if !entry.IsDir() &&
				strings.HasSuffix(entry.Name(), "_spice_gen.go") {
				return os.Remove(path)
			}
			return nil
		},
	); err != nil {
		t.Fatalf("remove copied generated shards: %v", err)
	}
	return destination
}
